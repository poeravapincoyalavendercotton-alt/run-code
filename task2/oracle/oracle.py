def _interp(KE, grid):
    n = len(_KE_GRID)
    if KE <= _KE_GRID[0]:
        return grid[0]
    if KE >= _KE_GRID[-1]:
        return grid[-1]
    i = bisect_left(_KE_GRID, KE)
    i0 = max(0, min(i - 2, n - 4))
    x = _KE_GRID[i0:i0 + 4]
    y = grid[i0:i0 + 4]
    out = 0.0
    for j in range(4):
        prod = 1.0
        for k in range(4):
            if k != j:
                prod *= (KE - x[k]) / (x[j] - x[k])
        out += y[j] * prod
    return out


_MAX_QUERIES = 3
_query_count = 0


def handle_query(mode, parameters):
    global _query_count
    if mode == "measure_tune":
        KE = parameters.get("KE_MeV")
        if KE is None:
            return {"error": "missing required parameter: KE_MeV"}
        try:
            KE = float(KE)
        except (TypeError, ValueError):
            return {"error": "KE_MeV must be a number (MeV)"}
        if not (_KE_MIN <= KE <= _KE_MAX):
            return {
                "error": (
                    f"KE_MeV={KE} outside valid range; "
                    f"expected {_KE_MIN} <= KE_MeV <= {_KE_MAX} MeV "
                    "(beam unstable outside this window)"
                )
            }
        if _query_count >= _MAX_QUERIES:
            return {
                "error": (
                    f"measure_tune budget exhausted: {_MAX_QUERIES} queries "
                    "already used this session. The beam instrumentation is "
                    "costly; plan your energy scan accordingly."
                ),
                "queries_used": _query_count,
            }
        _query_count += 1
        return {
            "KE_MeV": KE,
            "nu_x": _interp(KE, _NUX_GRID),
            "nu_y": _interp(KE, _NUY_GRID),
            "queries_used": _query_count,
            "queries_remaining": _MAX_QUERIES - _query_count,
        }
    return {"error": f"unknown mode: {mode}; supported: measure_tune"}
